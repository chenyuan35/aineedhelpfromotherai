import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = path => JSON.parse(fs.readFileSync(path, 'utf8'));
const id = 'truemove-validity-pack-th-2026';
const base = 'frontend/tools/phone-number-lifecycle-mvp/';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const snapshot = read('data/phone/v1/snapshots.json').find(x => x.routeId === id && x.kind === 'current-profile');
const route = routes.find(x => x.id === id);
const metrics = read(base + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
const index = read(base + 'phone-search-index.json').routes.find(x => x.id === id);
const summary = read(base + 'phone-route-summaries.json').routes.find(x => x.id === id);
const detail = read(base + 'phone-route-data/' + id + '.json');
assert(route && snapshot && metrics && index && summary && detail);
assert.equal(routes.length, 160);
assert.equal(sources.length, 858);
assert.equal(route.sourceIds.length, 13);
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(snapshot.checkedAt, '2026-10-08');
assert.equal(snapshot.data.landedCost.landedOriginal, null);
assert.equal(snapshot.data.keep.observedActionCost, 15);
assert.equal(snapshot.data.keep.yearCostOriginal, null);
assert.equal(snapshot.data.keep.intervalDays, 180);
assert.match(snapshot.data.keep.action, /THB3\/30d/);
assert.match(snapshot.data.keep.action, /max 180d/);
assert.match(snapshot.data.kyc, /Tourist SIM/);
assert.match(snapshot.data.chinaActivation, /China/);
assert.match(snapshot.data.roamingSms, /unverified/);
assert.equal(snapshot.data.guideEligible, false);
assert.equal(snapshot.data.avoidRoute, true);
assert.equal(metrics.acquisitionCostOriginal, null);
assert.equal(metrics.keepYearCostOriginal, null);
assert.equal(summary.decisionFacts.sourceCount, 13);
assert.equal(index.eventCount, 9);
assert.equal(events.length, 9);
assert.equal(observations.length, 0);
assert(events.some(x => x.type === 'expiry-number-retention'));
assert(events.some(x => x.type === 'tourist-ineligibility'));
assert(events.some(x => x.type === 'roaming-sms-operational-failure'));
assert.equal(detail.sources.length, 13);
assert.equal(detail.events.length, 9);
assert.equal(detail.observations.length, 0);
for (const sid of route.sourceIds) assert(sources.some(s => s.id === sid && s.url.startsWith('https://')));
assert.equal(read(base + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(base + 'comparison-route-index.json').routeCount, 135);
assert.equal(Object.values(read(base + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
console.log('TrueMove Thailand conditional extension, post-expiry retention, tourist exclusion, HOLD and public boundary passed.');
