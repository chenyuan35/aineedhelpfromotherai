import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {originalDiscussionKey} from './phone-original-discussion.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const get=f=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const routes=get('data/phone/v1/routes.json'),sources=get('data/phone/v1/sources.json');
const events=get('data/phone/v1/events.json'),snapshots=get('data/phone/v1/snapshots.json');
const generic=routes.find(x=>x.id==='tello-us'),payg=routes.find(x=>x.id==='tello-paygo-credit-2026');
assert(generic&&payg);
const official=sources.filter(x=>x.url==='https://tello.com/help_center/account-payments/when-will-my-phone-number-expire');
assert.equal(official.length,1,'one current official URL, not duplicate source per cohort');
const reddit=sources.filter(x=>x.url?.includes('/comments/1wx3k90/'));
assert.equal(reddit.length,1,'one independent original Reddit discussion, not one per commenter');
assert.equal(reddit[0].type,'first-hand-community-thread');
assert.equal(official[0].type,'provider-official');
assert(generic.sourceIds.includes(official[0].id)&&payg.sourceIds.includes(official[0].id));
assert(generic.sourceIds.includes(reddit[0].id)&&!payg.sourceIds.includes(reddit[0].id));
const grace=snapshots.filter(x=>x.kind==='number-expiry-grace'&&[generic.id,payg.id].includes(x.routeId));
assert.equal(grace.length,2,'two distinct cohorts, never one combined grace');
const g=grace.find(x=>x.routeId===generic.id),p=grace.find(x=>x.routeId===payg.id);
assert.equal(g.data.graceDays,12);assert.equal(p.data.graceDays,7);
assert.equal(g.checkedAt,'2026-10-12');assert.equal(p.checkedAt,'2026-10-12');
assert(g.sourceId===official[0].id&&p.sourceId===official[0].id);
assert.match(g.data.summary,/12-day/);assert.match(g.data.summary,/not/i);
assert.match(p.data.summary,/3 months|three months/i);assert.match(p.data.summary,/7-day/);
assert.match(p.data.summary,/NOT a recommended 97-day/);
assert.match(g.data.summary,/PAYG/);
const threadEvents=events.filter(x=>x.sourceId===reddit[0].id);
assert.equal(threadEvents.length,3,'original OP + contrary support + expired recovery are one original');
assert.deepEqual(threadEvents.map(x=>x.authorHandle).sort(),['Luckiest_Corner','SpaceCaseSixtyTenV2','stefpix'].sort());
assert(threadEvents.every(x=>x.routeId===generic.id));
assert.equal(new Set(threadEvents.map(x=>originalDiscussionKey(reddit[0]))).size,1);
assert.equal(events.filter(x=>x.sourceId===reddit[0].id&&x.reportedAt!==undefined).length,1,'no made-up reply calendar dates');
const post=threadEvents.find(x=>x.authorHandle==='stefpix');
assert.match(post.outcome,/not someone who actually lost their number/);
assert.match(post.outcome,/NOT proof that active PAYG never preserves a line/);
const support=threadEvents.find(x=>x.authorHandle==='Luckiest_Corner');
assert.match(support.outcome,/phone support/);
assert.match(support.outcome,/not a personally tested/);
const recovery=threadEvents.find(x=>x.authorHandle==='SpaceCaseSixtyTenV2');
assert.match(recovery.outcome,/around a MONTH/);
assert.match(recovery.outcome,/received a refund/);
assert.match(recovery.outcome,/CONTRADICTS/);
assert.match(recovery.outcome,/NOT be recommended/);
assert.equal(events.filter(x=>x.sourceId===reddit[0].id && /sms-verification|OTP/i.test(x.type)).length,0);
const rawHtml=fs.readFileSync(path.join(root,'frontend/tools/phone-number-lifecycle-mvp/index.html'),'utf8');
assert.match(rawHtml,/kind==='number-expiry-grace'/);
assert.match(rawHtml,/Expiry safety window/);
assert.match(rawHtml,/grace\.data\?\.summary/);
for(const route of [generic,payg]){
 const detail=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/'+route.id+'.json');
 assert(detail.sources.some(x=>x.id===official[0].id));
 assert(detail.snapshots.some(x=>x.kind==='number-expiry-grace'&&x.sourceId===official[0].id));
 assert(detail.route.sourceIds.includes(official[0].id));
}
const genericDetail=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/tello-us.json');
assert.equal(genericDetail.events.filter(x=>x.sourceId===reddit[0].id).length,3);
const paygDetail=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/tello-paygo-credit-2026.json');
assert(!paygDetail.events.some(x=>x.sourceId===reddit[0].id));
const summary=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes;
for(const r of [generic,payg])assert.equal(summary.find(x=>x.id===r.id).decisionFacts.sourceCount,r.sourceIds.length);
console.log('Tello grace rule: monthly 12d vs PAYG 3mo+7d, 3 distinct authors / 1 original with rare recovery contradicting provider guarantee, UI and original-linked evidence PASS');
