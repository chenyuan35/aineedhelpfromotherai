import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const id = 'claro-pre-br-90d-2026';
const base = 'frontend/tools/phone-number-lifecycle-mvp/';
const route = read('data/phone/v1/routes.json').find(x => x.id === id);
const sources = read('data/phone/v1/sources.json');
const snap = read('data/phone/v1/snapshots.json').find(x => x.routeId === id && x.kind === 'current-profile');
const ev = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const details = read(base + 'phone-route-data/' + id + '.json');
const sum = read(base + 'phone-route-summaries.json').routes.find(x => x.id === id);
const index = read(base + 'phone-search-index.json').routes.find(x => x.id === id);
const metric = read(base + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
assert(route && snap && details && sum && metric && index);
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(route.sourceIds.length, 13);
assert(sources.length >= 791, 'Corpus must not regress below verified Claro source baseline');
for(const sid of route.sourceIds) assert(sources.some(x => x.id === sid && x.url.startsWith('https://')));
assert.equal(snap.checkedAt, '2026-10-08');
assert.equal(snap.data.landedCost.landedOriginal, null);
assert.equal(snap.data.keep.observedActionCost, 35);
assert.equal(snap.data.keep.yearCostOriginal, 140);
assert.equal(snap.data.keep.intervalDays, 90);
assert.match(snap.data.keep.action, /360 days/);
assert.match(snap.data.keep.action, /ambiguous/);
assert.match(snap.data.roamingSms, /unavailable/i);
assert.match(snap.data.chinaActivation, /outside Brazil/);
assert.match(snap.data.kyc, /physical stores/);
assert.equal(snap.data.guideEligible, false);
assert.equal(observations.length, 0);
assert.equal(ev.length, 7);
assert(ev.some(x => x.type === 'roaming-restriction'));
assert(ev.some(x => x.type === 'cost-boundary'));
assert.equal(sum.decisionFacts.sourceCount, 13);
assert.equal(sum.eventCount, 7);
assert.equal(sum.metrics.keepYearCostOriginal, 140);
assert.equal(index.metrics.acquisitionCostOriginal, null);
assert.equal(metric.acquisitionCostOriginal, null);
assert.equal(metric.keepYearCostOriginal, 140);
assert.equal(details.events.length, 7);
assert.equal(details.sources.length, 13);
assert.equal(details.observations.length, 0);
assert.equal(read('data/phone/v1/routes.json').length, 160);
assert.equal(read(base + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(base + 'comparison-route-index.json').routes.length, 135);
assert.equal(Object.values(read(base + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
console.log('Claro Brazil prepaid maintenance passed.');
