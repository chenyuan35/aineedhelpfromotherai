import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {originalDiscussionKey} from './phone-original-discussion.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const get=f=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const routes=get('data/phone/v1/routes.json'),sources=get('data/phone/v1/sources.json');
const events=get('data/phone/v1/events.json'),obs=get('data/phone/v1/observations.json');
const gen=routes.find(x=>x.id==='tello-us'),payg=routes.find(x=>x.id==='tello-paygo-credit-2026');
assert(gen&&payg&&gen.evidenceState==='needs-reconciliation'&&payg.surfaceState==='backstage-only');
const ids=[['1p4bspo','reddit-tello-korean-card-renewal-1p4bspo-20251123','2025-11-23',['jerichoi224','ObjectNotIdentified']],['1wc8ej8','reddit-tello-korea-foreign-esim-1wc8ej8-20260910','2026-09-10',['pilotboiz','ReasonablenessDude','imshanejaz']]];
for(const [thread,id,reportedAt,authors] of ids){
 const matched=sources.filter(x=>x.url?.includes('/comments/'+thread+'/'));
 assert.equal(matched.length,1,thread+' original source dedup');assert.equal(matched[0].id,id);
 assert.equal(matched[0].reportedAt,reportedAt);assert.equal(matched[0].type,'first-hand-community-thread');
 assert(gen.sourceIds.includes(id));assert(!payg.sourceIds.includes(id),'Monthly and mixed cohorts must not enter PAYG-only route');
 const es=events.filter(x=>x.sourceId===id);
 assert.equal(es.length,authors.length,'One author-level claim, no comment duplication');
 assert.deepEqual(es.map(x=>x.authorHandle).sort(),authors.slice().sort());
 assert(es.every(x=>x.routeId===gen.id && /NOT|not|unknown|unspecified|MONTHLY|MONTHLY|billed|plan/i.test(x.productCohort)));
 assert.equal(obs.filter(x=>x.sourceId===id).length,0,'No named-app OTP was actually tested');
 assert.equal(new Set(es.map(x=>originalDiscussionKey(matched[0]))).size,1);
}
const first=events.find(x=>x.id==='evt-tello-1p4bspo-jerichoi224-korean-renewal-failure');
assert.match(first.outcome,/US card was added successfully/);assert.match(first.outcome,/CHARGE was only pending\/unknown/);
assert.match(first.outcome,/EMAIL WARNING/);assert.match(first.productCohort,/NOT PAYG-only/);
const pp=events.find(x=>x.id==='evt-tello-1p4bspo-objectnotidentified-paypal-accounts');
assert(pp && pp.reportedAt===undefined && /NOT prove a Korean\/foreign bank card/.test(pp.outcome));
const korea=events.find(x=>x.id==='evt-tello-1wc8ej8-pilotboiz-korea-new-monthly-payg-addon');
assert.match(korea.outcome,/international roaming explicitly rejected/);assert.match(korea.outcome,/Tello SMS appeared/);
assert.match(korea.outcome,/activation-failed notification/);assert.match(korea.outcome,/NOT report a named-bank/);
const fail=events.find(x=>x.id==='evt-tello-1wc8ej8-imshanejaz-provisioning-refund');
assert(fail && fail.reportedAt===undefined && /refund/.test(fail.outcome));
const win=events.find(x=>x.id==='evt-tello-1wc8ej8-reasonablenessdude-wifi-no-payg');
assert(win && win.reportedAt===undefined && /International Roaming was disabled/.test(win.outcome));
const summaries=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes;
assert.equal(summaries.find(x=>x.id===gen.id).decisionFacts.sourceCount,gen.sourceIds.length);
assert.equal(summaries.find(x=>x.id===payg.id).decisionFacts.sourceCount,payg.sourceIds.length);
assert.equal(summaries.find(x=>x.id===payg.id).serviceEvidence.length,0);
const html=fs.readFileSync(path.join(root,'frontend/tools/phone-number-lifecycle-mvp/index.html'),'utf8');
assert.match(html,/esc\(e.productCohort\)/,'Product cohort is visible beside firsthand evidence');
assert.match(html,/esc\(e.authorHandle\)/,'Commenter and OP must be attributable');
assert.match(html,/esc\(x.independentSourceCount\?\?'unknown'\)/,'Original discussion count must be shown alongside n');
assert.match(html,/x.label\|\|x.id/,'Original source title must identify payment vs first activation');
const detail=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/tello-us.json');
assert(detail.sources.some(x=>x.id===ids[0][1]));assert(detail.sources.some(x=>x.id===ids[1][1]));
assert.equal(detail.events.filter(x=>ids.some(v=>v[1]===x.sourceId)).length,5);
assert.equal(detail.observations.filter(x=>ids.some(v=>v[1]===x.sourceId)).length,0);
const paygDetail=get('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/tello-paygo-credit-2026.json');
assert(paygDetail.snapshots.some(x=>x.kind==='current-profile'&&/United States/.test(x.data?.chinaActivation||'')));
assert(!paygDetail.sources.some(x=>ids.some(v=>v[1]===x.id)));
console.log('Tello buyer cohort: two distinct Reddit originals, five authors, foreign card pending vs first-US roaming gate, zero invented OTP, generic vs PAYG isolation — PASS');
