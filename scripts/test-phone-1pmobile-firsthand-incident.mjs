import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const base='data/phone/v1/';
const routeId='1pmobile-uk-2026';
const url='https://www.reddit.com/r/1pmobile/comments/1wa0ole/what_time_do_1p_mobile_port_numbers_in/';
const sources=read(base+'sources.json'), events=read(base+'events.json'), observations=read(base+'observations.json'),routes=read(base+'routes.json');
const hits=sources.filter(x=>x.url===url);
assert.equal(hits.length,1,'One original thread is one source, regardless of replies');
const src=hits[0];
assert.equal(src.type,'first-hand-community-thread');
const route=routes.find(x=>x.id===routeId);
assert(route.sourceIds.includes(src.id),'original thread must be attached to only relevant route');
assert.equal(route.evidenceState,'admitted');
assert.equal(route.surfaceState,'backstage-only');
const report=events.filter(x=>x.sourceId===src.id);
assert.equal(report.length,1,'No duplicate event for two different authors within same thread');
assert.equal(report[0].authorHandle,'fursty_ferret');
assert.match(report[0].scope,/Three-to-1p/);
assert.match(report[0].scope,/palacepaulse25/);
assert.match(report[0].outcome,/external inbound SMS remained absent/);
assert.match(report[0].outcome,/unverified/);
assert.match(report[0].outcome,/ONE original thread/);
assert.equal(report[0].resolution,'unverified-author-linkage');
assert.equal(observations.filter(x=>x.sourceId===src.id).length,0,'Ambiguous OTP batch reply MUST NOT be an app success or failure outcome');
const other=events.find(x=>x.id==='evt-1pmobile-esim-incoming-sms-voice-failure-20260427');
assert(other&&/reported returning to O2 by 2026-05-17/.test(other.outcome));
const amex=observations.find(x=>x.id==='obs-1pmobile-1sxe5k1-jackoboy9-amex-20260517');
assert.equal(amex?.outcome,'failure');
assert.equal(amex?.authorHandle,'jackoboy9');
const generated=read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/1pmobile-uk-2026.json');
assert(generated.events?.some(x=>x.id===report[0].id),'Public on-demand evidence detail must include the incident');
assert(generated.sources?.some(x=>x.id===src.id),'Evidence detail must expose original provenance URL');
const index=read('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes.find(x=>x.id===routeId);
assert(index,'Indexed route missing');
assert.equal(index.surfaceState,'backstage-only');
assert(!index.serviceEvidence?.some(x=>x.serviceId==='whatsapp'&&x.sampleSize>0),'Port-in thread cannot manufacture WhatsApp outcomes');
const recoveryUrl='https://www.reddit.com/r/1pmobile/comments/1vs2kjd/how_long_does_porting_takes/';
const recoverySources=sources.filter(x=>x.url===recoveryUrl);
assert.equal(recoverySources.length,1,'One SMARTY-to-1p original thread, one source');
assert(route.sourceIds.includes(recoverySources[0].id));
const recoveryEvents=events.filter(x=>x.sourceId===recoverySources[0].id);
assert.equal(recoveryEvents.length,1,'The same author initial failure and recovery cannot be two independent source samples');
const timeline=recoveryEvents[0];
assert.equal(timeline.authorHandle,'COBHC95');
assert.match(timeline.scope,/EXISTING SMARTY number/);
assert.match(timeline.outcome,/SAME author later confirmed incoming SMS and OTP resumed/);
assert.match(timeline.outcome,/RCS remained broken/);
assert.match(timeline.outcome,/NOT a named-app success/);
assert.match(timeline.outcome,/not a guaranteed restoration SLA/);
assert.equal(timeline.resolution,'same-author-inbound-sms-and-unspecified-otp-recovered-2026-08-19');
assert.equal(observations.filter(x=>x.sourceId===recoverySources[0].id).length,0,'Generic OTP recovery is NOT an app operation');
assert(generated.events?.some(x=>x.id===timeline.id));
assert(generated.sources?.some(x=>x.id===recoverySources[0].id));
assert.equal(index.decisionFacts.sourceCount,11,'Source count includes separate originals, not commenters');
console.log('1pMobile port evidence: two distinct originals; one ambiguous, one same-author recovered; no invented named-app results — PASS');
