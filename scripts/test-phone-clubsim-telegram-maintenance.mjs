import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const observations = read('data/phone/v1/observations.json');
const detail = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/clubsim-sms-pack-6hkd-2026.json');
const summary = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes.find(x => x.id === 'clubsim-sms-pack-6hkd-2026');
const route = routes.find(x => x.id === 'clubsim-sms-pack-6hkd-2026');
assert(route);
const ids = ["shuzijumin-clubsim-telegram-success-20240321","v2ex-clubsim-telegram-failure-20240412","linuxdo-clubsim-telegram-failure-20250219","v2ex-clubsim-telegram-mnp-failure-20251101","naixi-clubsim-telegram-conflict-20260729","naixi-clubsim-telegram-success-20260918","v2ex-clubsim-telegram-conditional-20260918"];
for (const id of ids) { assert(route.sourceIds.includes(id)); assert(sources.some(x => x.id === id)); }
const obs = observations.filter(x => x.routeId === route.id && x.service === 'Telegram' && x.operation === 'registration-verification');
assert.equal(obs.length, 7);
assert.equal(new Set(obs.map(x => x.sourceId)).size, 7);
const agg = detail.serviceEvidence.find(x => x.serviceId === 'telegram' && x.operation === 'registration-verification');
assert(agg);
assert.equal(agg.sampleSize, 7);
assert.equal(agg.independentSourceCount, 7);
assert.equal(agg.successCount, 2);
assert.equal(agg.failureCount, 3);
assert.equal(agg.mixedCount, 2);
assert.equal(agg.percentageEligible, true);
assert.equal(agg.successRatePct, 28.6);
assert.equal(agg.grade, 'C');
assert(summary);
const sag = summary.serviceEvidence.find(x => x.serviceId === 'telegram' && x.operation === 'registration-verification');
assert.equal(sag.successRatePct, 28.6);
assert.equal(summary.decisionFacts.sourceCount, 11);
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.evidenceState, 'admitted');
