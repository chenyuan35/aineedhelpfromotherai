import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const observations = read('data/phone/v1/observations.json');
const detail = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/ultra-mobile-paygo-3-2026.json');
const summary = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes.find(x => x.id === 'ultra-mobile-paygo-3-2026');
const route = routes.find(x => x.id === 'ultra-mobile-paygo-3-2026');
assert(route);
const ids = ['reddit-ultramobile-telegram-signup-20250117','youtube-didushan-ultramobile-telegram-20250221','shuzijumin-ultramobile-telegram-20250307','linuxdo-ultramobile-telegram-mixed-20250603','v2ex-ultramobile-telegram-mixed-20260404'];
for (const id of ids) { assert(route.sourceIds.includes(id)); assert(sources.some(x => x.id === id)); }
const obs = observations.filter(x => x.routeId === route.id && x.service === 'Telegram' && x.operation === 'registration-verification');
assert.equal(obs.length, 5);
assert.equal(new Set(obs.map(x => x.sourceId)).size, 5);
assert.equal(new Set(obs.map(x => x.dedupeKey)).size, 5);
assert.equal(obs.filter(x => x.outcome === 'success').length, 3);
assert.equal(obs.filter(x => x.outcome === 'mixed').length, 2);
const agg = detail.serviceEvidence.find(x => x.serviceId === 'telegram' && x.operation === 'registration-verification');
assert(agg);
assert.equal(agg.sampleSize, 5);
assert.equal(agg.independentSourceCount, 5);
assert.equal(agg.successCount, 3);
assert.equal(agg.failureCount, 0);
assert.equal(agg.mixedCount, 2);
assert.equal(agg.percentageEligible, true);
assert.equal(agg.successRatePct, 60);
assert.equal(agg.grade, 'C');
assert(summary);
const sag = summary.serviceEvidence.find(x => x.serviceId === 'telegram' && x.operation === 'registration-verification');
assert(sag);
assert.equal(sag.successRatePct, 60);
assert.equal(sag.grade, 'C');
assert.equal(summary.decisionFacts.sourceCount, 8);
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.evidenceState, 'admitted');
console.log('Ultra Mobile Telegram evidence maintenance OK');
