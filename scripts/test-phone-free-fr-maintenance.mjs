import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const root = 'frontend/tools/phone-number-lifecycle-mvp/', id = 'free-mobile-fr-2026';
const routes = read('data/phone/v1/routes.json'), sources = read('data/phone/v1/sources.json');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const snap = read('data/phone/v1/snapshots.json').find(x => x.routeId === id && x.kind === 'current-profile');
const route = routes.find(x => x.id === id);
const metric = read(root + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
const index = read(root + 'phone-search-index.json').routes.find(x => x.id === id);
const summary = read(root + 'phone-route-summaries.json').routes.find(x => x.id === id);
const detail = read(root + 'phone-route-data/' + id + '.json');
assert(route && snap && metric && index && summary && detail);
assert.equal(routes.length, 160);
assert(sources.length >= 814);
assert.equal(route.sourceIds.length, 14);
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(snap.checkedAt, '2026-10-08');
assert.equal(snap.data.landedCost.landedOriginal, 10);
assert.equal(snap.data.landedCost.landedCny, null);
assert.equal(snap.data.keep.yearCostOriginal, 24);
assert.match(snap.data.keep.action, /recurring/);
assert.match(snap.data.kyc, /stable link/);
assert.match(snap.data.payment, /RIB/);
assert.match(snap.data.payment, /3D Secure/);
assert.match(snap.data.roamingSms, /Option Voyage/);
assert.match(snap.data.roamingSms, /China/);
assert.match(snap.data.roamingSms, /€9.70\/MB/);
assert.match(snap.data.wifiCalling, /cellular network/);
assert.equal(snap.data.guideEligible, false);
assert.equal(metric.acquisitionCostOriginal, 10);
assert.equal(metric.acquisitionCostCny, null);
assert.equal(metric.keepYearCostOriginal, 24);
assert.equal(summary.decisionFacts.sourceCount, 14);
assert.equal(summary.decisionFacts.kycState, 'unclear');
assert.equal(index.eventCount, 9);
assert.equal(events.length, 9);
assert.equal(observations.length, 0);
assert(events.some(e => e.type === 'community-operational-success'));
assert(events.some(e => e.type === 'community-operational-failure'));
for (const sid of route.sourceIds) assert(sources.some(x => x.id === sid && x.url.startsWith('https://')));
assert.equal(detail.sources.length, 14);
assert.equal(detail.events.length, 9);
assert.equal(detail.observations.length, 0);
assert.equal(read(root + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(root + 'comparison-route-index.json').routeCount, 135);
assert.equal(Object.values(read(root + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
console.log('Free Mobile France recurring contract, Voyage advance, SMS and HOLD maintenance passed.');
