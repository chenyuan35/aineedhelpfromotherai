import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => JSON.parse(fs.readFileSync(path, 'utf8'));
const root = 'frontend/tools/phone-number-lifecycle-mvp/';
const id = 'asda-mobile-uk-2026';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const route = routes.find(x => x.id === id);
const snap = read('data/phone/v1/snapshots.json').find(x => x.routeId === id && x.kind === 'current-profile');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const metric = read(root + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
const summary = read(root + 'phone-route-summaries.json').routes.find(x => x.id === id);
const index = read(root + 'phone-search-index.json').routes.find(x => x.id === id);
const detail = read(root + 'phone-route-data/' + id + '.json');
assert(route && snap && metric && summary && index && detail);
assert.equal(routes.length, 160);
assert.equal(sources.length, 802);
assert.equal(route.sourceIds.length, 13);
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(snap.checkedAt, '2026-10-08');
assert.equal(snap.data.landedCost.landedOriginal, 5);
assert.equal(snap.data.landedCost.landedCny, null);
assert.equal(snap.data.keep.observedActionCost, 5);
assert.equal(snap.data.keep.yearCostOriginal, 10);
assert.equal(snap.data.keep.intervalDays, 180);
assert.match(snap.data.keep.action, /BOTH/i);
assert.match(snap.data.keep.action, /90 further days/);
assert.match(snap.data.payment, /UK-address-registered Visa\/Mastercard/);
assert.match(snap.data.roamingSms, /World Group 1/);
assert.match(snap.data.roamingSms, /bank\/OTP/);
assert.match(snap.data.chinaActivation, /China-first/);
assert.match(snap.data.kyc, /not explicitly specify/);
assert.equal(snap.data.guideEligible, false);
assert.equal(events.length, 8);
assert.equal(observations.length, 0);
assert(events.some(x => x.type === 'lifecycle-rule-conflict'));
assert(events.some(x => x.type === 'credit-expiry-and-number-loss'));
for (const sid of route.sourceIds) assert(sources.some(x => x.id === sid && x.url.startsWith('https://')));
assert.equal(metric.acquisitionCostOriginal, 5);
assert.equal(metric.acquisitionCostCny, null);
assert.equal(metric.keepYearCostOriginal, 10);
assert.equal(summary.decisionFacts.sourceCount, 13);
assert.equal(summary.decisionFacts.kycState, 'unclear');
assert.equal(index.metrics.keepYearCostOriginal, 10);
assert.equal(index.metrics.acquisitionCostCny, null);
assert.equal(detail.sources.length, 13);
assert.equal(detail.events.length, 8);
assert.equal(detail.observations.length, 0);
assert.equal(read(root + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(root + 'comparison-route-index.json').routeCount, 135);
assert.equal(Object.values(read(root + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
console.log('ASDA UK PAYG dual-180-day rule, payment and roaming HOLD maintenance passed.');
