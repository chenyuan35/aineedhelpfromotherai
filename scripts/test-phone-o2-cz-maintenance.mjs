import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const id='o2-cz-prepaid-2026',base='frontend/tools/phone-number-lifecycle-mvp/';
const route=read('data/phone/v1/routes.json').find(x=>x.id===id);
const sources=read('data/phone/v1/sources.json');
const profile=read('data/phone/v1/snapshots.json').find(x=>x.routeId===id&&x.kind==='current-profile');
const events=read('data/phone/v1/events.json').filter(x=>x.routeId===id);
const observations=read('data/phone/v1/observations.json').filter(x=>x.routeId===id);
const summaries=read(base+'phone-route-summaries.json').routes;
const summary=summaries.find(x=>x.id===id);
const detail=read(base+'phone-route-data/'+id+'.json');
assert(route&&profile&&summary&&detail);
assert.equal(route.surfaceState,'backstage-only');assert.equal(route.evidenceState,'admitted');assert.equal(route.lastVerifiedAt,'2026-10-08');
assert.equal(route.sourceIds.length,9);for(const source of route.sourceIds)assert(sources.some(x=>x.id===source),'missing source '+source);
assert.equal(profile.checkedAt,'2026-10-08');assert.equal(profile.data.landedCost.landedOriginal,99);
assert.equal(profile.data.keep.observedActionCost,300);assert.equal(profile.data.keep.yearCostOriginal,300);assert.equal(profile.data.keep.intervalDays,365);
assert.match(profile.data.keep.action,/6 months/);assert.match(profile.data.keep.action,/12 months/);
assert.match(profile.data.acquisitionSummary,/CZK29/);assert.match(profile.data.chinaActivation,/store/);
assert.match(profile.data.payment,/Europe/);assert.match(profile.data.roamingSms,/free/);
assert.match(profile.data.wifiCalling,/does not support/);assert.equal(profile.data.guideEligible,false);
assert(events.some(x=>x.type==='cost-boundary'));assert(events.some(x=>x.type==='activation-boundary'));
assert.equal(observations.length,0);assert.equal(summary.decisionFacts.sourceCount,9);assert.equal(summary.metrics.keepYearCostOriginal,300);
assert.equal(summary.metrics.keepIntervalDays,365);assert.equal(summaries.length,160);
assert.equal(detail.sources.length,9);assert.equal(detail.events.length,events.length);assert.equal(detail.observations.length,0);
assert.equal(read(base+'comparison-route-index.json').routes.length,135);
assert.equal(Object.values(read(base+'publication-policy.json').routeStates).filter(x=>x==='indexable').length,3);
console.log('O2 Czech prepaid maintenance passed.');
