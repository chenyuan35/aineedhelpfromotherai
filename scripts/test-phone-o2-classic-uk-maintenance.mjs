import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const id='o2-uk-classic-payg-6mo-2026',root='frontend/tools/phone-number-lifecycle-mvp/';
const routes=read('data/phone/v1/routes.json'),sources=read('data/phone/v1/sources.json');
const events=read('data/phone/v1/events.json').filter(x=>x.routeId===id);
const observations=read('data/phone/v1/observations.json').filter(x=>x.routeId===id);
const snap=read('data/phone/v1/snapshots.json').find(x=>x.routeId===id&&x.kind==='current-profile');
const route=routes.find(x=>x.id===id),metric=read(root+'phone-route-metrics.json').metrics.find(x=>x.routeId===id);
const index=read(root+'phone-search-index.json').routes.find(x=>x.id===id);
const summary=read(root+'phone-route-summaries.json').routes.find(x=>x.id===id);
const detail=read(root+'phone-route-data/'+id+'.json');
assert(route&&snap&&metric&&index&&summary&&detail);
assert.equal(routes.length,160);assert(sources.length>=835);
assert.equal(route.sourceIds.length,13);assert.equal(route.evidenceState,'hold');
assert.equal(route.surfaceState,'backstage-only');assert.equal(route.lastVerifiedAt,'2026-10-08');
assert.equal(snap.checkedAt,'2026-10-08');
assert.equal(snap.data.landedCost.landedOriginal,null);
assert.equal(snap.data.landedCost.landedCny,null);
assert.equal(snap.data.keep.yearCostOriginal,null);
assert.equal(snap.data.keep.yearCostCny,null);
assert.equal(snap.data.keep.intervalDays,null);
assert.equal(snap.data.keep.observedActionCost,0.02);
assert.match(snap.data.keep.action,/six-calendar-month/);
assert.match(snap.data.keep.action,/top up, add a Bolt On OR make a chargeable activity/);
assert.match(snap.data.payment,/UK-bank-issued/);
assert.match(snap.data.wifiCalling,/NOT supported outside the UK/);
assert.match(snap.data.roamingSms,/China/);
assert.match(snap.data.simType,/unverified/);
assert.equal(snap.data.guideEligible,false);assert.equal(snap.data.avoidRoute,true);
assert.equal(metric.acquisitionCostOriginal,null);assert.equal(metric.keepYearCostOriginal,null);
assert.equal(metric.keepIntervalDays,null);
assert.equal(index.eventCount,10);assert.equal(summary.decisionFacts.sourceCount,13);
assert.equal(summary.decisionFacts.kycState,'unclear');
assert.equal(events.length,10);assert.equal(observations.length,0);
assert(events.some(x=>x.type==='community-number-access-loss'));
for(const sid of route.sourceIds)assert(sources.some(x=>x.id===sid&&x.url.startsWith('https://')));
assert.equal(detail.sources.length,13);assert.equal(detail.events.length,10);assert.equal(detail.observations.length,0);
assert.equal(read(root+'phone-route-summaries.json').routes.length,160);
assert.equal(read(root+'comparison-route-index.json').routeCount,135);
assert.equal(Object.values(read(root+'publication-policy.json').routeStates).filter(x=>x==='indexable').length,3);
console.log('O2 UK Classic legacy six-month choices, UK-only funding and WiFi, null cost/HOLD and public boundary passed.');
