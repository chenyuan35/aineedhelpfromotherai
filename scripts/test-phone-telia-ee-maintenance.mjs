import fs from "node:fs";
import assert from "node:assert/strict";
const read = p => JSON.parse(fs.readFileSync(p, "utf8"));
const routeId = "telia-ee-180d-2026";
const routes = read("data/phone/v1/routes.json");
const sources = read("data/phone/v1/sources.json");
const observations = read("data/phone/v1/observations.json");
const events = read("data/phone/v1/events.json");
const detail = read(`frontend/tools/phone-number-lifecycle-mvp/phone-route-data/${routeId}.json`);
const summary = read("frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json").routes.find(x => x.id === routeId);
const route = routes.find(x => x.id === routeId);
assert(route);
assert.equal(route.surfaceState, "backstage-only");
assert.equal(route.evidenceState, "admitted");
assert.equal(route.lastVerifiedAt, "2026-10-05");
assert.equal(route.form, "physical + eSIM");
for (const id of ["official-super-esim-20261005","official-super-topup-20261005","official-super-roaming-20261005","official-super-price-update-20250723"]) {
  assert(route.sourceIds.includes(id));
  assert(sources.some(x => x.id === id));
}
for (const id of ["evt-telia-ee-current-lifecycle-20261005","evt-telia-ee-esim-activation-20261005","evt-telia-ee-roaming-boundary-20261005","evt-telia-ee-current-basic-tariff-20261005"]) assert(events.some(x => x.id === id));
assert.equal(observations.filter(x => x.routeId === routeId).length, 0);
assert.equal(detail.serviceEvidence.length, 0);
assert(summary);
assert.equal(summary.serviceEvidence.length, 0);
assert.equal(summary.decisionFacts.sourceCount, 5);
assert.equal(detail.metrics.acquisitionCostOriginal, 1);
assert.equal(detail.metrics.keepYearCostOriginal, 6);
assert.equal(detail.metrics.keepIntervalDays, 180);
const latest = detail.snapshots.at(-1);
assert.equal(latest.id, "snap-telia-ee-180d-2026-current-profile-20261005");
assert.equal(latest.data.simType, "physical + eSIM");
assert.equal(latest.data.keep.observedActionCost, 3);
assert.match(latest.data.keep.action, /single transaction|single top-up/i);
assert.match(latest.data.chinaActivation, /only be activated in Estonia|activated in Estonia/i);
assert.match(latest.data.refund, /30-day|30 day/i);
assert.match(latest.data.roamingSms, /EU|Outside the EU/i);
assert.match(latest.data.tariffSummary, /€0\.05/);
console.log("Telia Estonia Super maintenance OK");
