import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const routes = read('data/phone/v1/routes.json');
const brands = read('data/phone/v1/brands.json');
const sources = read('data/phone/v1/sources.json');
const observations = read('data/phone/v1/observations.json');
const events = read('data/phone/v1/events.json');
const policy = read('frontend/tools/phone-number-lifecycle-mvp/publication-policy.json');
const legacy = read('frontend/tools/phone-number-lifecycle-mvp/global-directory.json');
const ebay = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/redpocket-ebay-30-2026.json');
const essentials = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/redpocket-annual-2026.json');
const summaries = read('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes;

const route = routes.find(x => x.id === 'redpocket-ebay-30-2026');
assert(route, 'missing Red Pocket eBay $30 canonical route');
assert.equal(route.marketId, 'us');
assert.equal(route.networkId, 'att-us');
assert.equal(route.brandId, 'redpocket-ebay-us');
assert.equal(route.numberClass, 'real-mobile');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.evidenceState, 'admitted');
assert.equal(route.lastVerifiedAt, '2026-10-05');
assert.equal(route.sourceIds.length, 11);
const brand = brands.find(x => x.id === 'redpocket-ebay-us');
assert(brand);
assert.equal(brand.networkId, 'att-us');
for (const id of ['redpocket-ebay-30-listing-20261005','redpocket-annual-help-360d-20261005','redpocket-wifi-calling-20261005','redpocket-ebay-pin-20261005','site2us-redpocket-ebay-20260925','reddit-redpocket-ebay-lowcost-20260514','reddit-redpocket-ebay-abroad-activation-20260523','reddit-redpocket-ebay-roaming-conflict-20260825','reddit-redpocket-ebay-bangladesh-sms-20260627']) assert(sources.some(x => x.id === id), `missing ${id}`);
assert.equal(observations.filter(x => x.routeId === route.id).length, 0, 'do not manufacture service observations from route-level reports');
assert.equal(ebay.serviceEvidence.length, 0);
assert.equal(ebay.metrics.acquisitionCostOriginal, 30);
assert.equal(ebay.metrics.keepYearCostOriginal, 30);
assert.equal(ebay.metrics.keepIntervalDays, 360);
assert.equal(ebay.snapshots.at(-1).data.guideEligible, false);
assert.match(ebay.snapshots.at(-1).data.chinaActivation, /only be completed from the United States/i);
assert.match(ebay.snapshots.at(-1).data.roamingSms, /do not include roaming|do not rely/i);
assert(events.some(x => x.id === 'evt-redpocket-ebay-30-product-20261005'));
assert(events.some(x => x.id === 'evt-redpocket-ebay-30-overseas-boundary-20261005'));
assert(events.some(x => x.id === 'evt-redpocket-ebay-30-roaming-conflict-20261005'));
assert.equal(policy.routeStates[route.id], undefined, 'new backstage route must not gain a publication state');
assert.equal(legacy.routes.some(x => x.id === route.id), false, 'new route must not enter legacy public comparison');
assert(summaries.some(x => x.id === route.id), 'new route must be available in canonical finder summaries');

assert.equal(essentials.metrics.acquisitionCostOriginal, 80);
assert.equal(essentials.metrics.keepYearCostOriginal, 110);
assert.equal(essentials.metrics.keepIntervalDays, 360);
const currentEssentials = essentials.snapshots.at(-1).data;
assert.match(currentEssentials.acquisitionSummary, /Essentials annual product/i);
assert.match(currentEssentials.acquisitionSummary, /separate eBay/i);
assert.doesNotMatch(currentEssentials.guideSteps.join(' '), /buy \$60 annual/i);
assert(events.some(x => x.id === 'evt-redpocket-essentials-ebay-split-20261005'));

assert.equal(routes.length, 160);
assert.equal(brands.length, 157);
assert.ok(sources.length >= 651);
assert.equal(legacy.routes.length, 135);
assert.equal(Object.values(policy.routeStates).filter(x => x === 'indexable').length, 3);
console.log('Red Pocket eBay $30 atomic split OK: distinct 360-day route admitted backstage; Essentials cleaned; publication unchanged.');
