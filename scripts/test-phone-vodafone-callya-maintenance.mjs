import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const id = 'vodafone-callya-90d-2026', root = 'frontend/tools/phone-number-lifecycle-mvp/';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const snapshots = read('data/phone/v1/snapshots.json').filter(x => x.routeId === id && x.kind === 'current-profile');
const route = routes.find(x => x.id === id);
const current = snapshots.at(-1);
const historic = read('data/phone/review-packets/' + id + '.json');
const metrics = read(root + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
const index = read(root + 'phone-search-index.json').routes.find(x => x.id === id);
const summary = read(root + 'phone-route-summaries.json').routes.find(x => x.id === id);
const detail = read(root + 'phone-route-data/' + id + '.json');
const db = read(root + 'phone-database.json');
assert(route && current && historic && metrics && index && summary && detail && db);
assert.equal(routes.length, 160);
assert(sources.length >= 884);
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.evidenceState, 'hold');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(route.sourceIds.length, 15);
assert.equal(snapshots.length, 3);
assert.equal(snapshots[0].checkedAt, '2026-09-28'); // immutable historical parity
assert.equal(historic.sourceIds.length, 2);
assert.equal(current.checkedAt, '2026-10-08');
assert.equal(current.data.landedCost.landedOriginal, 0);
assert.equal(current.data.keep.yearCostOriginal, null);
assert.equal(current.data.keep.yearCostCny, null);
assert.equal(current.data.keep.observedActionCost, null);
assert.equal(current.data.keep.intervalDays, 90); // provider MAY terminate, not a prepaid billing cycle
assert.match(current.data.keep.action, /FOUR-WEEK/);
assert.match(current.data.keep.action, /MAY terminate/);
assert.match(current.data.keep.action, /No provider-mandated EUR20\/year top-up/);
assert.match(current.data.roamingSms, /China in zone 3/);
assert.match(current.data.roamingSms, /No independently confirmed/);
assert.match(current.data.chinaActivation, /CallYa M/);
assert.match(current.data.payment, /minimum.*NOT established/);
assert.equal(current.data.guideEligible, false);
assert.equal(current.data.avoidRoute, true);
assert.equal(metrics.keepYearCostOriginal, null);
assert.equal(metrics.keepYearCostCny, null);
assert.equal(summary.metrics.keepYearCostOriginal, null);
assert.equal(summary.decisionFacts.sourceCount, 15);
assert.equal(index.eventCount, 16);
assert.equal(events.length, 16);
assert.equal(observations.length, 0);
assert(events.some(x => x.type === 'provider-possible-inactivity-termination'));
assert(events.some(x => x.type === 'provider-china-sms-entitlement'));
assert(events.some(x => x.type === 'independent-adjacent-prearrival-success'));
assert.equal(detail.sources.length, 15);
assert.equal(detail.events.length, 16);
assert.equal(detail.snapshots.length, 3);
assert.equal(detail.observations.length, 0);
assert.deepEqual(db.routes, routes);
assert.deepEqual(db.sources, sources);
assert.equal(db.events.filter(x => x.routeId === id).length, 16);
assert.equal(db.snapshots.filter(x => x.routeId === id && x.kind === 'current-profile').length, 3);
for (const sid of route.sourceIds) assert(sources.some(x => x.id === sid && x.url.startsWith('https://')));
assert.equal(read(root + 'comparison-route-index.json').routeCount, 135);
assert.equal(Object.values(read(root + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
assert.equal(read(root + 'phone-route-summaries.json').routes.length, 160);
assert.equal(events.filter(x => x.sourceId === 'callya-vf-classic-china-deactivated-20260820').length, 3); // ONE user, correlated events
assert.equal(observations.length, 0);
assert.equal(current.data.keep.yearCostOriginal, null);
assert.match(current.data.holdReason, /China-based user reports inactivity cutoff/);
assert.equal(summary.decisionFacts.continuityRiskSignalCount, index.decisionFacts.continuityRiskSignalCount);
console.log('CallYa Classic no-fixed-quarterly-recharge, 90d warning, foreign eSIM/China SMS uncertainty and publication invariants passed.');
