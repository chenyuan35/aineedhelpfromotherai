import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const id = 'mts-sokhranyayu-nomer-2026';
const base = 'frontend/tools/phone-number-lifecycle-mvp/';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const snapshots = read('data/phone/v1/snapshots.json');
const events = read('data/phone/v1/events.json');
const observations = read('data/phone/v1/observations.json');
const summaryRows = read(base + 'phone-route-summaries.json').routes;
const detail = read(base + 'phone-route-data/' + id + '.json');
const route = routes.find(x => x.id === id);
const profile = snapshots.find(x => x.routeId === id && x.kind === 'current-profile');
const summary = summaryRows.find(x => x.id === id);
assert(route && profile && summary);
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(route.evidenceState, 'admitted');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.sourceIds.length, 12);
for (const sid of route.sourceIds) assert(sources.some(x => x.id === sid), 'missing source: ' + sid);
assert.equal(profile.checkedAt, '2026-10-08');
assert.equal(profile.data.keep.observedActionCost, 349);
assert.equal(profile.data.keep.yearCostOriginal, 698);
assert.equal(profile.data.keep.intervalDays, 180);
assert.equal(profile.data.guideEligible, false);
assert.match(profile.data.tariffSummary, /RUB1\.5\/day/);
assert.match(profile.data.chinaActivation, /Russian network/);
assert.match(profile.data.kyc, /biometric/i);
assert.match(profile.data.roamingSms, /24-hour|24 hours/);
assert.match(profile.data.holdReason, /OTP/);
const eventRows = events.filter(x => x.routeId === id);
assert(eventRows.some(x => x.type === 'lifecycle-reconciliation'));
assert(eventRows.some(x => x.type === 'operational-failure-adjacent'));
assert.equal(observations.filter(x => x.routeId === id).length, 0);
assert.equal(summary.decisionFacts.sourceCount, 12);
assert.equal(summary.metrics.keepYearCostOriginal, 698);
assert.equal(summary.metrics.keepIntervalDays, 180);
assert.equal(detail.sources.length, 12);
assert.equal(detail.events.length, eventRows.length);
assert.equal(detail.observations.length, 0);
assert.equal(summaryRows.length, 160);
assert.equal(read(base + 'comparison-route-index.json').routes.length, 135);
const indexable = Object.values(read(base + 'publication-policy.json').routeStates).filter(x => x === 'indexable');
assert.equal(indexable.length, 3);
console.log('MTS Russia retention maintenance passed.');
