import assert from 'node:assert/strict';
import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const page=fs.readFileSync(new URL('frontend/site/src/pages/tools/phone-number-survival-guide/directory/index.astro',root),'utf8');
const canon=JSON.parse(fs.readFileSync(new URL('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json',root),'utf8'));
const old=JSON.parse(fs.readFileSync(new URL('frontend/tools/phone-number-lifecycle-mvp/comparison-route-index.json',root),'utf8'));
assert.match(page,/canonicalRouteSummaries\(\)/);
assert.match(page,/\.dir-market\{[^}]*overflow-x:auto/, 'market table must scroll internally on narrow phones');
assert.match(page,/\.lb\{[^}]*overflow-x:auto/, 'low-cost table must not overflow whole page');
assert.match(page,/r\.numberClass === 'real-mobile' && r\.evidenceState === 'admitted'/);
assert.match(page,/Indicative low-cost retention options/);
assert.match(page,/Source dates and account eligibility matter/);
assert.match(page,/fetch\('\.\.\/phone-route-summaries\.json'/);
assert.match(page,/cny:hasCost\?m\.keepYearCostCny:null/);
assert.match(page,/keepLabel:hasCost/);
assert.match(page,/route=\$\{encodeURIComponent\(r\.id\)\}/);
assert(!page.includes('Cheapest keep-alive routes'));
assert(!page.includes('Cheapest first'));
assert(!page.includes('Ranked by annual keep-alive cost, normalized to CNY. Only routes with an established yearly cost are ranked.'));
