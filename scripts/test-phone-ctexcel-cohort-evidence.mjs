import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import { originalDiscussionKey } from './phone-original-discussion.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=f=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const route=read('data/phone/v1/routes.json').find(x=>x.id==='ctexcel-uk-2026');
const sources=read('data/phone/v1/sources.json'), events=read('data/phone/v1/events.json');
const snapshots=read('data/phone/v1/snapshots.json').filter(x=>x.routeId===route.id && x.kind==='current-profile');
const ids=['nodeseek-ctexcel-847511-esim-first-attach-20260729','nodeseek-ctexcel-867442-physical-wifi-20260810','nodeseek-ctexcel-869829-esim-dispute-20260812'];
const ss=ids.map(id=>sources.find(x=>x.id===id));
assert(ss.every(Boolean),'Every independent original must exist');
assert.equal(new Set(ss.map(x=>originalDiscussionKey(x))).size,3,'Do not count comments/replies as independent discussions');
assert(ss.every(x=>x.type==='first-hand-community-thread'));
assert(ss.every(x=>route.sourceIds.includes(x.id)));
const ownEvents=events.filter(x=>x.routeId===route.id && ids.includes(x.sourceId));
assert.equal(ownEvents.length,3,'one typed, author-scoped event for each original');
assert.equal(new Set(ownEvents.map(x=>x.authorHandle)).size,3);
assert(ownEvents.filter(x=>x.productCohort.includes('annual eSIM')).length>=2,'Separate newly bought annual eSIM buyers');
assert(ownEvents.some(x=>/physical SIM/i.test(x.productCohort)),'Keep physical-SIM cohort separate');
assert(ownEvents.some(x=>/final result unreported|outcome.*unknown|not establish actual/i.test(x.outcome)),'No invented refund/dispute completion');
assert(ownEvents.every(x=>!/registration-verification|otp-deliver/i.test(x.type)),'None tested named-app OTP');
assert(snapshots.some(x=>x.checkedAt==='2026-10-03'),'Preserve historical snapshot');
const snap=snapshots.find(x=>x.id==='snap-ctexcel-uk-2026-current-profile-20261014');
assert(snap);
const d=snap.data;
assert.equal(d.guideEligible,false);
assert(d.chinaActivation.includes('physical-SIM') && d.chinaActivation.includes('annual-eSIM'),'No cross-cohort China activation promise');
assert(d.chinaActivation.includes('not')||d.chinaActivation.includes('No provider-authorized'));
assert(/NOT proof every purchaser|NOT proof every|NOT/.test(d.kyc),'Passport recovery not universal initial KYC');
assert(/final result unreported/i.test(d.refund),'Pending dispute never marked recovered');
assert(d.landedCost.landedOriginal===null && d.keep.yearCostOriginal===null,'No invented cost');
assert.equal(route.evidenceState,'hold');
assert.equal(route.surfaceState,'backstage-only');
const summary=read('frontend/tools/phone-number-lifecycle-mvp/phone-route-summaries.json').routes.find(x=>x.id===route.id);
const detail=read('frontend/tools/phone-number-lifecycle-mvp/phone-route-data/ctexcel-uk-2026.json');
assert.equal(summary.decisionFacts.sourceCount,9);
assert.equal(summary.eventCount,4);
assert.equal(summary.observationCount,0);
assert.equal(summary.services.length,0);
assert.equal(summary.metrics.acquisitionCostOriginal,null);
assert.equal(summary.evidenceState,'hold');
assert.equal(detail.events.filter(x=>ids.includes(x.sourceId)).length,3);
assert.equal(detail.sources.filter(x=>ids.includes(x.id)).length,3);
assert.equal(detail.snapshots.filter(x=>x.kind==='current-profile').length,2);
console.log('CTExcel cohort reconciliation: three original authors, physical vs new eSIM, independent failures, no synthetic OTP, canonical/public HOLD — PASS');
