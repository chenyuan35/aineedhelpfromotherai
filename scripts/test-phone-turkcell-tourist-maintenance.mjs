import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = path => JSON.parse(fs.readFileSync(path, 'utf8'));
const id = 'turkcell-tourist-90d-blocker-2026';
const root = 'frontend/tools/phone-number-lifecycle-mvp/';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const snapshot = read('data/phone/v1/snapshots.json').find(x => x.routeId === id && x.kind === 'current-profile');
const route = routes.find(x => x.id === id);
const metrics = read(root + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
const index = read(root + 'phone-search-index.json').routes.find(x => x.id === id);
const summary = read(root + 'phone-route-summaries.json').routes.find(x => x.id === id);
const detail = read(root + 'phone-route-data/' + id + '.json');
const historic = read('data/phone/review-packets/' + id + '.json');
assert(route && snapshot && metrics && index && summary && detail && historic);
assert.equal(routes.length, 160);
assert.equal(sources.length, 867);
assert.equal(route.sourceIds.length, 11);
assert.equal(route.family, 'temporary');
assert.equal(route.numberClass, 'real-mobile');
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(snapshot.checkedAt, '2026-10-08');
assert.equal(snapshot.data.landedCost.landedOriginal, null);
assert.equal(snapshot.data.keep.yearCostOriginal, null);
assert.equal(snapshot.data.keep.observedActionCost, null);
assert.equal(snapshot.data.keep.intervalDays, null);
assert.match(snapshot.data.acquisitionSummary, /90-day application window is NOT a 90-day lifetime/);
assert.match(snapshot.data.keep.action, /repealed effective 2026-06-25/);
assert.match(snapshot.data.keep.action, /DIFFERENT tariff cohort/);
assert.match(snapshot.data.kyc, /biometric/);
assert.match(snapshot.data.chinaActivation, /Türkiye/);
assert.match(snapshot.data.roamingSms, /no current Tourist SIM entitlement/);
assert.equal(snapshot.data.guideEligible, false);
assert.equal(snapshot.data.avoidRoute, true);
assert.equal(metrics.acquisitionCostOriginal, null);
assert.equal(metrics.keepYearCostOriginal, null);
assert.equal(summary.decisionFacts.sourceCount, 11);
assert.equal(index.eventCount, 9);
assert.equal(events.length, 9);
assert.equal(observations.length, 0);
assert(events.some(x => x.type === 'passport-legacy-rule-repealed'));
assert(events.some(x => x.type === 'adjacent-regular-prepaid-lifecycle'));
assert(events.some(x => x.type === 'tourist-acquisition-mixed-outcome'));
assert(events.some(x => x.type === 'adjacent-overseas-sms-recovery'));
assert.equal(detail.sources.length, 11);
assert.equal(detail.events.length, 9);
assert.equal(detail.observations.length, 0);
assert.equal(historic.route.sourceIds.length, 2);
assert.equal(historic.snapshots[0].checkedAt, '2026-09-29');
for (const sid of route.sourceIds) assert(sources.some(s => s.id === sid && s.url.startsWith('https://')));
assert.equal(read(root + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(root + 'comparison-route-index.json').routeCount, 135);
assert.equal(Object.values(read(root + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
