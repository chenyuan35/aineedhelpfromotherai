import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const id = 'telstra-prepaid-longexpiry-2026';
const base = 'frontend/tools/phone-number-lifecycle-mvp/';
const routes = read('data/phone/v1/routes.json');
const sources = read('data/phone/v1/sources.json');
const snapshots = read('data/phone/v1/snapshots.json');
const events = read('data/phone/v1/events.json').filter(x => x.routeId === id);
const observations = read('data/phone/v1/observations.json').filter(x => x.routeId === id);
const route = routes.find(x => x.id === id);
const snapshot = snapshots.find(x => x.routeId === id && x.kind === 'current-profile');
const summary = read(base + 'phone-route-summaries.json').routes.find(x => x.id === id);
const detail = read(base + 'phone-route-data/' + id + '.json');
const index = read(base + 'phone-search-index.json').routes.find(x => x.id === id);
const metrics = read(base + 'phone-route-metrics.json').metrics.find(x => x.routeId === id);
assert(route && snapshot && summary && detail && index && metrics);
assert.equal(route.evidenceState, 'hold');
assert.equal(route.surfaceState, 'backstage-only');
assert.equal(route.lastVerifiedAt, '2026-10-08');
assert.equal(route.sourceIds.length, 9);
assert(sources.length >= 779, 'Source corpus must not regress below verified Telstra baseline');
assert.equal(routes.length, 160);
for (const sid of route.sourceIds) assert(sources.some(x => x.id === sid), 'missing source ' + sid);
assert.equal(snapshot.checkedAt, '2026-10-08');
assert.match(snapshot.data.acquisitionSummary, /Casual/);
assert.match(snapshot.data.acquisitionSummary, /395/);
assert.equal(snapshot.data.landedCost.landedOriginal, 74);
assert.equal(snapshot.data.keep.observedActionCost, 74);
assert.equal(snapshot.data.keep.yearCostOriginal, 74);
assert.equal(snapshot.data.keep.intervalDays, 365);
assert.match(snapshot.data.keep.action, /6-month recharge-only rescue window/);
assert.match(snapshot.data.kyc, /international passport/i);
assert.match(snapshot.data.chinaActivation, /not established/);
assert.match(snapshot.data.payment, /not confirmed/);
assert.match(snapshot.data.roamingSms, /reports/i);
assert.equal(snapshot.data.guideEligible, false);
assert.equal(events.length, 5);
assert.equal(observations.length, 0);
assert(events.some(x => x.type === 'cost-boundary'));
assert(events.some(x => x.type === 'operational-failure'));
assert.equal(summary.decisionFacts.sourceCount, 9);
assert.equal(summary.eventCount, 5);
assert.equal(summary.metrics.keepYearCostOriginal, 74);
assert.equal(index.metrics.keepYearCostOriginal, 74);
assert.equal(metrics.acquisitionCostOriginal, 74);
assert.equal(detail.sources.length, 9);
assert.equal(detail.events.length, 5);
assert.equal(detail.observations.length, 0);
assert.equal(read(base + 'phone-route-summaries.json').routes.length, 160);
assert.equal(read(base + 'comparison-route-index.json').routes.length, 135);
assert.equal(Object.values(read(base + 'publication-policy.json').routeStates).filter(x => x === 'indexable').length, 3);
console.log('Telstra Casual annual retention maintenance passed.');
